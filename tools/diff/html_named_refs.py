#!/usr/bin/env python3
"""Generate src/fmt/html_named_refs.zig: the named character references clamscan decodes in
HTML, observed black-box (docs/clean-room.md, "Named references").

  html_named_refs.py --entities DIR [--clamscan PATH] [--certs DIR] [--out FILE]

DIR holds the candidate name lists: the WHATWG `entities.json`
(https://html.spec.whatwg.org/entities.json) and the W3C ISO 8879 and HTML/MathML entity sets
(https://www.w3.org/2003/entities/iso8879/*.ent, https://www.w3.org/2003/entities/2007/htmlmathml-f.ent).
Every candidate name is written as `<i>&NAME;<i>` into one HTML file; clamscan --leave-temps
keeps its nocomment.html, where a decoded reference appears as its code point (one byte below
U+00FF, `&#xHHHH;` from there) and an unknown one as its name in lower case. Only the names and
the code points clamscan prints are used, so the table is an observation, not a copy of a list.
"""
import argparse
import glob
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile


def candidates(entdir):
    names = set()
    path = os.path.join(entdir, "entities.json")
    if os.path.exists(path):
        for k in json.load(open(path)):
            names.add(k.strip("&;"))
    for f in glob.glob(os.path.join(entdir, "*.ent")):
        for m in re.finditer(rb"<!ENTITY\s+([A-Za-z0-9.]+)\s", open(f, "rb").read()):
            names.add(m.group(1).decode())
    return sorted(n for n in names if re.fullmatch(r"[A-Za-z0-9]+", n))


def observe(names, clamscan, certs):
    work = tempfile.mkdtemp(prefix="zav-refs-")
    try:
        db = os.path.join(work, "none.ndb")
        open(db, "w").write("Diff.Nothing:0:*:f1e2d3c4b5a69788796a5b4c3d2e1f00\n")
        doc = os.path.join(work, "refs.html")
        open(doc, "wb").write(b"<html>" + b"".join(b"<i>&" + n.encode() + b";<i>\n" for n in names))
        tmp = os.path.join(work, "tmp")
        os.makedirs(tmp)
        cmd = [clamscan, "--no-summary", "--bytecode=no", "-d", db, "--leave-temps", "--tempdir=" + tmp, doc]
        if certs:
            cmd.insert(1, "--cvdcertsdir=" + certs)
        subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, env=dict(os.environ, LC_ALL="C"))
        nc = open(glob.glob(os.path.join(tmp, "*", "html-tmp.*", "nocomment.html"))[0], "rb").read()
    finally:
        shutil.rmtree(work, ignore_errors=True)
    vals = nc[len(b"<html>"):].split(b"<i>")[1::2]
    if len(vals) < len(names):
        sys.exit("html_named_refs.py: clamscan's output has %d fields for %d names" % (len(vals), len(names)))
    table = []
    for n, v in zip(names, vals):
        if v == ("&" + n.lower() + ";").encode():
            continue
        m = re.fullmatch(rb"&#x([0-9a-f]{4});", v)
        if m:
            cp = int(m.group(1), 16)
        elif len(v) == 1:
            cp = v[0]
        else:
            sys.exit("html_named_refs.py: unexpected output %r for &%s;" % (v, n))
        table.append((n, cp))
    return table


HEADER = """//! Named character references clamscan 1.5.4 decodes in HTML, with the code points it
//! prints for them. Generated by tools/diff/html_named_refs.py from black-box observation:
//! each candidate name (from the WHATWG entities.json and the W3C ISO 8879 and HTML/MathML
//! entity sets) was presented to clamscan and the code point read back from its normalised
//! output. Names are case-sensitive; any name not listed is left as text.
//! Do not edit by hand.

/// Sorted by name (byte order), for binary search.
pub const refs = [_]struct { []const u8, u16 }{
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--entities", required=True)
    ap.add_argument("--clamscan", default=os.environ.get("CLAMSCAN", "clamscan"))
    ap.add_argument("--certs", default=os.environ.get("CLAMAV_CERTS"))
    ap.add_argument("--out", default="src/fmt/html_named_refs.zig")
    args = ap.parse_args()
    names = candidates(args.entities)
    table = observe(names, args.clamscan, args.certs)
    table.sort(key=lambda t: t[0].encode())
    with open(args.out, "w") as f:
        f.write(HEADER)
        for n, cp in table:
            f.write('    .{ "%s", 0x%04x },\n' % (n, cp))
        f.write("};\n")
    print("html_named_refs.py: %d candidates, %d decoded" % (len(names), len(table)))


if __name__ == "__main__":
    main()
